#!/usr/bin/env bash
set -euo pipefail

echo "==> Setting up clean build directory on ext4..."
BUILD_DIR="/tmp/proofreturn-fe-build"
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"
cd "$BUILD_DIR"

echo "==> Copying frontend project files..."
cp /mnt/c/Users/renal/Downloads/ProofReturn/package*.json .
mkdir -p apps packages
cp -r /mnt/c/Users/renal/Downloads/ProofReturn/apps/* apps/
cp -r /mnt/c/Users/renal/Downloads/ProofReturn/packages/* packages/

# Remove any Windows-generated artifacts
find . -type d -name "node_modules" -prune -exec rm -rf {} +
find . -type d -name ".next" -prune -exec rm -rf {} +

echo "==> Running npm ci --ignore-scripts (Linux x86_64)..."
npm ci --ignore-scripts

echo "==> Verifying next build on Linux..."
(cd apps/demo-storefront && npx next build)

echo "==> Packaging node_modules-linux.tar.xz..."
mkdir -p /mnt/c/Users/renal/Downloads/ProofReturn/audit-bundle
tar -cJf /mnt/c/Users/renal/Downloads/ProofReturn/audit-bundle/node_modules-linux.tar.xz \
    node_modules \
    $(ls -d apps/*/node_modules packages/*/node_modules 2>/dev/null || true)

echo "==> Done! Archive created at /mnt/c/Users/renal/Downloads/ProofReturn/audit-bundle/node_modules-linux.tar.xz"
ls -lh /mnt/c/Users/renal/Downloads/ProofReturn/audit-bundle/node_modules-linux.tar.xz
